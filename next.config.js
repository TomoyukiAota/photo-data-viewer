// In Vercel, for pdv-in-plm project, the following settings are required:
// - In "Build & Development Settings", OUTPUT DIRECTORY needs to be .next_plm
// - In "Environment Variables", set PDV_IN_PLM=True

const distDirForPlm = '.next_plm';
const isPdvInPlm = process.env.PDV_IN_PLM === 'True';

/** @type {import('next').NextConfig} */
module.exports = {
  // Change distDir so that running "npm run dev:plm" and "npm run dev" do not collide.
  distDir: isPdvInPlm ? distDirForPlm : module.exports.distDir,

  reactStrictMode: true,
  webpack(config, { isServer, dev }) {
    // libheif-js is generated by Emscripten, and its code to run on Node.js
    // calls require() in a way webpack cannot statically resolve. That code is
    // not used to decode HEIF files in this app because the WebAssembly binary
    // is embedded in libheif-js/wasm-bundle. Ignore the warning about it.
    config.ignoreWarnings = [
      ...(config.ignoreWarnings ?? []),
      {
        module: /node_modules[\\/]libheif-js[\\/]/,
        message: /Critical dependency: require function is used/,
      },
    ];

    if (!isServer) {
      // This is to avoid the "Module not found: Can't resolve 'fs'" error.
      // Reference: https://github.com/vercel/next.js/issues/7755#issuecomment-812805708
      config.resolve.fallback.fs = false;

      // The deployment in Photo Location Map is built for a browser, as the standalone one is, with the default
      // config.target. Photo Location Map's isolated window has no Node.js, and gives the photo through its bridge
      // (src/app-integration/plm-bridge.ts). An earlier version's window has Node.js, and there this app reads the
      // photo with Electron's own require (src/app-integration/local-photo-file.ts).
      if (isPdvInPlm && dev) {
        // Older Electron Chromium treats eval(TrustedScript) as a no-op.
        // Keep development module evaluation compatible; production is unchanged.
        delete config.output.trustedTypes;
      }
    }

    return config;
  },
};
